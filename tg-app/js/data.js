// Определение архетипа по баллам
function getArchetype(scores) {
  const s = scores;
  const archetypeScores = {
    investigator: s.analytics * 0.6 + s.tech * 0.4,
    creator:      s.creativity * 0.6 + s.social * 0.4,
    helper:       s.social * 0.6 + s.organization * 0.4,
    master:       s.nature * 0.6 + s.analytics * 0.4,
    organizer:    s.organization * 0.6 + s.social * 0.4,
    pioneer:      s.creativity * 0.6 + s.analytics * 0.4
  };
  return Object.entries(archetypeScores)
    .sort((a, b) => b[1] - a[1])[0][0];
}

// Косинусное сходство профилей
function cosineSimilarity(userScores, profScores) {
  const dims = Object.keys(userScores);
  const dot = dims.reduce((s, d) => s + (userScores[d] || 0) * (profScores[d] || 0), 0);
  const magUser = Math.sqrt(dims.reduce((s, d) => s + (userScores[d] || 0) ** 2, 0));
  const magProf = Math.sqrt(dims.reduce((s, d) => s + (profScores[d] || 0) ** 2, 0));
  return magUser && magProf ? dot / (magUser * magProf) : 0;
}

